import { createEnvironmentInjector, EnvironmentInjector, Injector } from '@angular/core';
import { StorageEngine } from '../src/lib/storage/storage-engine';
import { provideStore } from '../src/lib/store/provide';
import { Store } from '../src/lib/store/store';
import {
  bridgeBudgets,
  bridgeReducers,
  countingDriver,
  exerciseBridgeCost,
} from './bridge-cost-workload';
import { assert, environment, report } from './common';

// Captured with the extended acceptance workload before production changes.
// Includes all driver calls, BEGIN/COMMIT, internal sql.js queries and refresh.
const before = {
  cold: [23, 6, 5, 5, 3, 15, 1014, 1012, 3, 5, 505, 611],
  active: [26, 9, 8, 8, 6, 15, 1014, 1012, 6, 8, 508, 615],
};

export async function bridgeCost(): Promise<void> {
  const results: Record<string, Record<string, number>> = {};
  for (const active of [false, true]) {
    const { driver, counts } = countingDriver();
    const parent = Injector.create({ providers: [] });
    const injector = createEnvironmentInjector(
      [provideStore(bridgeReducers, { sqlite: { driver } })],
      parent as EnvironmentInjector,
    );
    try {
      const result = await exerciseBridgeCost(
        injector.get(Store),
        counts,
        active,
        (actual, expected) => assert.deepEqual(actual, expected),
      );
      results[active ? 'active' : 'cold'] = result.report;
      for (const [name, budget] of Object.entries(bridgeBudgets))
        assert.ok(result.report[name] <= budget, `${name}: ${result.report[name]} > ${budget}`);
      console.log('bridgeCost', JSON.stringify({ active, ...result.report }));
    } finally {
      await injector.get(StorageEngine).close();
      injector.destroy();
      parent.destroy();
    }
  }
  const rows = Object.entries(bridgeBudgets).map(
    ([name, budget], i) =>
      `| ${name} | ${before.cold[i]} | ${results['cold'][name]} | ${before.active[i]} | ${results['active'][name]} | ${budget} |`,
  );
  await report(
    'bridge-cost',
    `# Bridge cost: phase 11

${environment}


Counts are individual run/query/exec calls per complete dispatchAsync action, including BEGIN/COMMIT, sql.js's internal last_insert_rowid query, and post-commit refresh. No multi-statement exec masking. Cold starts without subscriptions; active pins the entire store before measuring. State assertions/materialize and reseeding happen outside measured actions (identical before/after workload). Both modes use 500 entities and three scalar extras, plus a 300-element pointer array. Shared workload: spikes/bridge-cost-workload.ts; enforced by src/lib/entity/bridge-cost.spec.ts.

The brief's original two-extra-property workload measured reset at 1016; the extended three-property workload below resets exactly 500 rows after add/remove and measured 1014. Before counts were captured from the extended failing acceptance tests before implementation; after counts are regenerated by npm run spikes. This measures statement complexity, not Android bridge latency.

| Operation | Before cold | After cold | Before active | After active | Budget |
| --- | ---: | ---: | ---: | ---: | ---: |
${rows.join('\n')}
`,
  );
}
